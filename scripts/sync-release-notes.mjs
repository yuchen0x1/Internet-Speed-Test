// Generate the root changelog from the canonical version history.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const canonical = fs.readFileSync(path.join(root, "docs/releases/release-notes.md"), "utf8").replace(/\r\n/g, "\n");
const mirrorPath = path.join(root, "CHANGELOG.md");
const marker = "本文件是完整日志的维护入口；根目录 `CHANGELOG.md` 为同步镜像。";
const mirror = "<!-- Generated by npm run docs:sync; edit docs/releases/release-notes.md. -->\n\n" + canonical
  .replace(/^# .+\n/, "# Changelog\n")
  .replace(marker, "本文件由 [完整更新日志](release-notes.md) 自动同步；请修改该维护入口后运行 `npm run docs:sync`。")
  .replace(/\]\(([^\s)]+)\)/g, (match, target) => {
    if (/^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(target)) return match;
    return `](${path.posix.normalize(path.posix.join("docs/releases", target))})`;
  });

const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  fs.writeFileSync(mirrorPath, mirror);
  console.log("Updated CHANGELOG.md from docs/releases/release-notes.md");
} else if (mode === "--check") {
  const actual = fs.readFileSync(mirrorPath, "utf8").replace(/\r\n/g, "\n");
  if (actual !== mirror) throw new Error("CHANGELOG.md is out of sync. Run npm run docs:sync.");
  const versions = [...canonical.matchAll(/^## v(\d+\.\d+\.\d+)\b/gm)].map((m) => m[1]);
  if (new Set(versions).size !== versions.length) throw new Error("Duplicate version sections.");
  for (const version of versions) {
    if (!canonical.includes(`<a id="v${version.replaceAll(".", "-")}"></a>`)) {
      throw new Error(`Missing stable anchor for ${version}`);
    }
  }
  for (const [name, text] of [["docs/releases/release-notes.md", canonical], ["CHANGELOG.md", mirror]]) {
    for (const [, target] of text.matchAll(/\]\(([^\s)]+)\)/g)) {
      if (/^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(target)) continue;
      if (!fs.existsSync(path.resolve(root, path.dirname(name), target.split("#")[0]))) {
        throw new Error(`${name}: missing local link ${target}`);
      }
    }
  }
  console.log(`Release documentation in sync: ${versions.length} versions and local links checked`);
} else {
  throw new Error("Usage: node scripts/sync-release-notes.mjs --write|--check");
}
